import { chromium } from '@playwright/test';
import { mkdir,writeFile } from 'node:fs/promises';
await mkdir('test-results',{recursive:true});
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--enable-webgl','--ignore-gpu-blocklist']});
const page=await browser.newPage({viewport:{width:1440,height:960},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
await page.goto('http://localhost:5173');await page.waitForFunction(()=>window.__pond?.inspect().time>2);await page.screenshot({path:'test-results/desktop.png'});
console.log(JSON.stringify({initial:await page.evaluate(()=>window.__pond.inspect()),errors},null,2));
await writeFile('test-results/initial.json',JSON.stringify({initial:await page.evaluate(()=>window.__pond.inspect()),errors},null,2));
await browser.close();
